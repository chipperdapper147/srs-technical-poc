import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

const script = fileURLToPath(new URL("./check-pr-description.sh", import.meta.url));
const run = (title: string, body: string) =>
  spawnSync("bash", [script], {
    env: { ...process.env, PR_TITLE: title, PR_BODY: body },
    encoding: "utf8",
  });

describe("check-pr-description.sh", () => {
  it("passes a clean description, including a plain claude.ai/code link", () => {
    const r = run(
      "Add a thing",
      "## What\n\nStuff.\n\n🤖 Generated with [Claude Code](https://claude.ai/code)",
    );
    assert.equal(r.status, 0, r.stderr);
  });

  it("fails on a session URL in the body, as the PR tool's footer adds it", () => {
    const r = run(
      "Add a thing",
      "Stuff.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01AbCdEf)_",
    );
    assert.equal(r.status, 1);
    assert.match(r.stderr, /links to a Claude session/);
  });

  it("fails on a Claude-Session trailer line, in any case", () => {
    assert.equal(run("t", "text\nclaude-session: https://example.test/x").status, 1);
  });

  it("checks the title too", () => {
    assert.equal(run("See claude.ai/code/session_01x", "").status, 1);
  });

  it("treats the text as data, not shell", () => {
    const r = run("$(touch /tmp/pwned)", "`echo hi` $HOME");
    assert.equal(r.status, 0);
  });
});
